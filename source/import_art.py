"""Turn Twain's landmark SVGs (art/<CODE>.svg, 120x120, strokes only) into landmark-art.js.
Keeps the paths in the order they were drawn, lightly simplifies them, and drops colours and widths (the site sets those)."""
import os, re, json, math
SRC = os.path.dirname(os.path.abspath(__file__))

def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1; L = math.hypot(dx, dy) or 1e-9
    i, dmax = 0, 0
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / L
        if d > dmax: i, dmax = k, d
    if dmax > eps: return rdp(pts[:i + 1], eps)[:-1] + rdp(pts[i:], eps)
    return [pts[0], pts[-1]]

def convert(d):
    # polyline paths (M/L) are simplified; anything with curves is kept as written
    if re.search(r'[CcQqSsTtAaHhVvZz]', d) or re.search(r'[a-z]', d.replace('e', '')):
        return re.sub(r'\s+', ' ', d).strip()
    pts = [(float(a), float(b)) for a, b in re.findall(r'(-?[\d.]+)[ ,]+(-?[\d.]+)', d)]
    pts = rdp(pts, .12)
    return 'M' + ' L'.join(f'{x:g},{y:g}' for x, y in ((round(x, 1), round(y, 1)) for x, y in pts))

art = {}
for f in sorted(os.listdir(os.path.join(SRC, 'art'))):
    if not f.lower().endswith('.svg'): continue
    s = open(os.path.join(SRC, 'art', f), encoding='utf-8').read()
    ds = [convert(d) for d in re.findall(r'\sd="([^"]+)"', s)]
    ds = [d for d in ds if re.search(r'[LlHhVvCcQqSsTtAaZz]', d)]  # drop move-only paths that draw nothing
    art[f[:-4].upper()] = ds
    print(f, len(ds), 'paths')
open(os.path.join(SRC, 'landmark-art.js'), 'w').write('/* generated by import_art.py from art/*.svg */\nvar LANDMARK_ART = ' + json.dumps(art, separators=(',', ':')) + ';\n')
